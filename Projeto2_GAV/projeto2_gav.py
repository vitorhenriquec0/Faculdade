# Produto vetorial
prod_vetorial = np.cross(u, v)
norma = np.linalg.norm(prod_vetorial)
prod_vetorial = (prod_vetorial / norma) * 3 # diminuir o tamanho do vetor, por ex: * 0.5

# Criar figuras
fig = go.Figure()

# Vetor u
fig.add_traces(vetor(O, u, nome="u", cor="blue"))


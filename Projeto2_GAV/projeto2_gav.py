# Produto vetorial (perpendicular aos dois)
fig.add_traces(vetor(O, prod_vetorial, nome="produto vetorial", cor="black"))

# Layout
fig.update_layout(scene=dict(aspectmode='cube'), title="Produto Vetorial de u e v")

fig.show()